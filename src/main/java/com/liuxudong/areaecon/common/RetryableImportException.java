package com.liuxudong.areaecon.common;

/**
 * 可重试的异常 —— 用来标记"这次失败是临时性的，过几秒再试很可能就好了"。
 *
 * ==========================================================================
 * 【为什么要有这个类？重试的成败全在"异常分类"上】
 * ==========================================================================
 * 很多人写重试是这样：
 *
 *     try { doImport(); } catch (Exception e) { retry(); }
 *
 * 一行代码就实现了重试，但它是错的 —— 因为 Exception 是个大箩筐，
 * 里面装着两类**性质完全相反**的失败：
 *
 *   ① 临时性故障（重试有意义）
 *        数据库连接池耗尽、连接被服务端掐断、死锁被回滚、查询超时、
 *        对方系统 503、网络抖动
 *      特点：**过一会儿自己就好了**。重试是标准解法。
 *
 *   ② 确定性失败（重试一万次结果都一样）
 *        Excel 表头写错了、第 800 行有个空字段、文件被删了、超过 5 万行上限、
 *        SQL 语法写错了
 *      特点：**重试只是把同一个错误重复执行 N 遍**，用户还要多等 7 秒
 *            （1s + 2s + 4s），最后看到一条一模一样的错误信息。
 *
 * 所以重试框架里第一件事永远是"分类"，而不是"重试"。
 *
 * ==========================================================================
 * 【怎么判断一个异常属于哪一类 —— 三个判据】
 * ==========================================================================
 *   1. 换个时间点重试，结果会不会变？
 *        连接断了 → 会变（网络恢复了就能连上）  → 可重试
 *        数据非法 → 不会变（数据就在文件里躺着） → 不可重试
 *
 *   2. 是不是"资源"层面的问题（连接、锁、超时、带宽），而不是"内容"层面的问题？
 *        资源 → 可重试；内容 → 不可重试
 *
 *   3. 已经做了多少工作？重试的代价大不大？
 *        我们的 upsert 是幂等的，重试代价只是"再花几秒"，可以放心重试；
 *        如果每行要发一条短信，重试就会重复发 —— 那种场景必须先做去重再谈重试。
 *
 * 具体到本项目的判断逻辑，见 ImportServiceImpl#isRetryable。
 *
 * ==========================================================================
 * 【为什么要单独定义这个类，而不是直接判 DataAccessException？】
 * ==========================================================================
 * 因为有些"临时故障"不是 Spring 的数据访问异常：
 *   - 调用第三方接口返回 503（HttpServerErrorException）
 *   - 对象存储上传超时
 * 这些场景需要一个**语义明确**的标记："我看到的是临时故障，值得重试"。
 * 有了这个类，业务代码只要 `throw new RetryableImportException(...)`，
 * 上层的分类逻辑就不用改。
 *
 * 另外，它也是今天做故障注入实验的载体 —— 见 ImportServiceImpl#writeAllInBatches，
 * 那里会主动抛这个异常来模拟"第 N 批写库时数据库连接中断"。
 * 用真实异常类型（比如 DataAccessResourceFailureException）去模拟会让日志很迷惑：
 * 明明数据库是好的，却报"连不上数据库"。用一个自定义类，日志一眼能看出是人为注入的。
 */
public class RetryableImportException extends RuntimeException {

    public RetryableImportException(String message) {
        super(message);
    }

    public RetryableImportException(String message, Throwable cause) {
        super(message, cause);
    }
}
