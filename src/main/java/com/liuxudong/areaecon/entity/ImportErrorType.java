package com.liuxudong.areaecon.entity;

import lombok.Getter;

/**
 * 导入错误类型枚举。
 *
 * ==========================================================================
 * 【为什么要把错误分"类型"，而不是只存一句话？】
 * ==========================================================================
 * 假设一个 1 万行的文件里有 3000 行错误。只存一句话的话，用户能做的只有
 * "一行一行看" —— 3000 行，看完就放弃了。
 *
 * 分了类型之后，系统可以告诉他：
 *      "3000 行错误里，2680 行是'周期类型填了中文'（占 89%），
 *        剩下 320 行是'指标值为负'。"
 * 用户立刻知道：**只要把周期类型那一列全改成 M/Q/Y，绝大部分问题就解决了。**
 *
 * 这就是"分类"的价值：它把一堆零散的报错，压缩成一条可执行的行动建议。
 *
 * ==========================================================================
 * 【为什么用枚举，而不是字符串常量？】
 * ==========================================================================
 * 字符串常量的问题是"没有约束"：一个地方写 "BAD_PERIOD_TYPE"，
 * 另一个地方手滑写 "BAD_PERIODE_TYPE"，编译能过、运行不报错，
 * 统计时却会分裂成两组 —— 而且这种错只有对着数据看才会发现。
 * 枚举把错误类型的取值收缩到编译期就能检查的范围里。
 *
 * ==========================================================================
 * 【code 和 label 分开存的意义】
 * ==========================================================================
 * 数据库里存 code（英文、短、稳定），界面上显示 label（中文、可改）。
 * 如果哪天要把"周期类型非法"改成"周期类型只能是 Y/Q/M"，
 * 只改 label 就行，**历史数据不用刷**。
 * 反过来，如果把中文直接存进数据库，文案一改，历史数据和新数据就对不上了。
 * （这条规则对所有"状态 / 类型"字段都成立。）
 */
@Getter
public enum ImportErrorType {

    /** 必填列为空 */
    EMPTY_REQUIRED("必填项为空"),

    /** 整行没有任何数据（Excel 末尾常见的空行） */
    EMPTY_ROW("整行为空"),

    /** 周期类型不是 Y / Q / M */
    BAD_PERIOD_TYPE("周期类型非法"),

    /** 指标值是负数 */
    NEGATIVE_VALUE("指标值为负"),

    /** 指标值那一列填了 "abc" 之类，连数字都不是 */
    BAD_NUMBER("数值格式错误"),

    /** 文件总行数超过导入上限 */
    OVER_LIMIT("超出导入行数上限"),

    /** 兜底 */
    OTHER("其他错误");

    /** 给用户看的中文说明。存库时用 name()，展示时用 label */
    private final String label;

    ImportErrorType(String label) {
        this.label = label;
    }

    /**
     * 从 code 反查枚举。查不到返回 OTHER，绝不抛异常。
     *
     * 【为什么查不到不抛异常】
     * 因为这个方法主要用在"把数据库里的字符串转回枚举"的场景。
     * 万一某条历史数据的 error_type 是旧版本写的、新版本已经删了这个枚举值，
     * 抛异常会让整个统计接口 500 —— 那用户就彻底看不到错误报告了。
     * **展示类的逻辑，遇到不认识的数据要降级，不能崩。**
     */
    public static ImportErrorType of(String code) {
        if (code == null) {
            return OTHER;
        }
        for (ImportErrorType t : values()) {
            if (t.name().equals(code)) {
                return t;
            }
        }
        return OTHER;
    }

    /** 取中文名，查不到就给原始 code（至少不会显示成 null） */
    public static String labelOf(String code) {
        if (code == null) {
            return OTHER.label;
        }
        for (ImportErrorType t : values()) {
            if (t.name().equals(code)) {
                return t.label;
            }
        }
        return code;
    }
}
