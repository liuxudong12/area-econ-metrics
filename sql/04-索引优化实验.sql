USE area_econ;

-- -------------------------------------------------------------
-- 第 0 步：优化前的状态
-- -------------------------------------------------------------
-- 当时 fact_indicator_value 上只有两个索引：
--   PRIMARY (id)
--   uk_fact (region_code, indicator_code, period_code)   ← 业务唯一索引
--
-- 而被优化的这条 SQL 是这样的（只看它的"过滤条件"和"分组"）：
--
--   WHERE period_type = 'Y'
--     AND period_code IN ('2024','2025','2026')
--     AND indicator_code IN (...)          ← 由 JOIN dim_indicator 提供
--   GROUP BY period_code
--
-- ★ 关键观察：整条 SQL 里**从头到尾没有出现 region_code**。
--   而 uk_fact 的最左列正好是 region_code。
--   B+ 树索引必须从最左列开始才能定位入口，最左列缺失 → 索引用不上 → 全表扫描。

-- 优化前的实测结果（跑 10 次取平均，下同）：
--   平均耗时    133.45 ms
--   扫描行数    489,618
--   EXPLAIN     table=f  type=ALL  key=NULL  rows=487354
--                Extra=Using where; Using join buffer (hash join)


-- -------------------------------------------------------------
-- 第 1 步：候选方案 A —— 普通联合索引（三列）
-- -------------------------------------------------------------
-- 设计思路：把"过滤用的列"按顺序放进索引，让 B+ 树能从最左列开始定位。
--   period_type   等值条件（= 'Y'）→ 放最左，缩小范围
--   period_code   范围条件（IN 三个值）→ 放第二
--   indicator_code 等值条件（JOIN 带过来的）→ 放第三
--
-- 这个顺序的依据：等值条件在最左、范围条件在其后。
--   （反过来把 period_code 放最左就不行了 —— IN 是多个区间，后面的列没法再用来定位）

-- ALTER TABLE fact_indicator_value ADD INDEX idx_tpi (period_type, period_code, indicator_code);

-- 实测结果：
--   平均耗时    9.14 ms      （提速 14.6 倍）
--   扫描行数    5,418        （从 48.9 万降到 5 千）
--   EXPLAIN     table=f  type=range  key=idx_tpi  rows=5400
--                Extra=Using index condition; Using where
--   索引体积    27.6 MB → 43.1 MB（+15.5 MB）


-- -------------------------------------------------------------
-- 第 2 步：候选方案 B —— 覆盖索引（五列）
-- -------------------------------------------------------------
-- 思路：在 A 的基础上，把 SQL 里用到的**其他列也放进索引**，
--       这样查询只读索引、完全不用回表（回表 = 拿索引里的主键再去聚簇索引取整行）。
--
--   加 deleted        因为 WHERE 里有 f.deleted = 0
--   加 indicator_value 因为 SELECT 里有 SUM(f.indicator_value)

-- ALTER TABLE fact_indicator_value ADD INDEX idx_tpi_cov
--   (period_type, period_code, indicator_code, deleted, indicator_value);

-- 实测结果：
--   平均耗时    4.95 ms      （比 A 再快约 1.8 倍）
--   扫描行数    5,418
--   索引体积    27.6 MB → 49.2 MB（+21.6 MB）


-- -------------------------------------------------------------
-- 第 3 步：决策 —— 为什么最终选了 A 而不是更快的 B
-- -------------------------------------------------------------
--   A（三列）：9.14 ms，索引 +15.5 MB
--   B（五列）：4.95 ms，索引 +21.6 MB
--
-- 多花 6 MB 索引空间，换来 4 毫秒。
-- 对一个每天被调用几百次的接口来说，这 4 毫秒没人在意；
-- 但每次写入都要多维护一份索引、磁盘也多占 6 MB。
--
-- 所以选择 A。
-- ★ 面试加分点：主动说出"我试过覆盖索引，能再快一倍，但权衡后没选" ——
--   这证明的是"你会权衡"，而不是"你背了答案"。


-- =============================================================
-- 最终采用的优化语句（这个才是要留在生产环境里的）
-- =============================================================

ALTER TABLE fact_indicator_value
    ADD INDEX idx_tpi (period_type, period_code, indicator_code);


